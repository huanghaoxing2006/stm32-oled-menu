/**
 * 清屏：把显存全部写 0，并刷新
 */
void OLED_Clear(void)
{
    memset(OLED_GRAM, 0x00, sizeof(OLED_GRAM));

    uint8_t page, col;
    for (page = 0; page < 8; page++)
    {
        OLED_SetPos(page, 0);
        /* 一次发一整页 128 字节数据 */
        HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR << 1, OLED_DATA, I2C_MEMADD_SIZE_8BIT,
                          OLED_GRAM[page], 128, 1000);
    }
}

/**
 * 在 (x, y) 显示一个字符，x 是列(像素，0~127)，y 是页(0~7)
 */
void OLED_ShowChar(uint8_t x, uint8_t y, char ch)
{
	uint8_t num = ch - ' ';
	
	OLED_SetPos(y,x);
	HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR << 1, OLED_DATA, I2C_MEMADD_SIZE_8BIT,(uint8_t *)&Font8x16[num][0], 8, 1000);
	OLED_SetPos(y+1,x);
	HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR << 1, OLED_DATA, I2C_MEMADD_SIZE_8BIT,(uint8_t *)&Font8x16[num][8], 8, 1000);

}

