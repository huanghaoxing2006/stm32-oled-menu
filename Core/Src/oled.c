/* 显存缓冲区：128*64 = 8 页 * 128 列，共 1024 字节 */
static uint8_t OLED_GRAM[8][128];

/* 内部函数声明 */
static void OLED_WriteCmd(uint8_t cmd);
static void OLED_WriteData(uint8_t data);
static void OLED_SetPos(uint8_t page, uint8_t col);

/**
 * I2C 地址扫描：从 1 到 127 逐个试探，看哪个地址有设备应答。
 * 打印所有应答的设备地址（7位）。用于排查 OLED 真实地址/接线问题。
 */
void I2C_Scan(void)
{
    uint8_t addr;
    printf("[SCAN] I2C devices found:\r\n");
    for (addr = 1; addr < 127; addr++)
    {
        /* 发一个"写"请求探测，超时设短一点，避免每个空地址卡 100ms */
        if (HAL_I2C_IsDeviceReady(&hi2c1, addr << 1, 1, 10) == HAL_OK)
        {
            printf("  addr 0x%02X (7bit) = 0x%02X (8bit write)\r\n", addr, addr << 1);
        }
    }
    printf("[SCAN] done.\r\n");
}

/* ============ 底层：写命令 / 写数据 ============ */

/**
 * 发一个命令：控制字节 0x00 + 命令码
 * 用 HAL_I2C_Mem_Write，把 0x00 作为"内存地址"参数传入
 */
static void OLED_WriteCmd(uint8_t cmd)
{
    HAL_StatusTypeDef ret;
    ret = HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR << 1, OLED_CMD, I2C_MEMADD_SIZE_8BIT, &cmd, 1, 100);
    if (ret != HAL_OK)
    {
        printf("[CMD] I2C error: %d\r\n", ret);
    }
}

/**
 * 发一个数据：控制字节 0x40 + 数据
 */
static void OLED_WriteData(uint8_t data)
{
    HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR << 1, OLED_DATA, I2C_MEMADD_SIZE_8BIT, &data, 1, 100);
}

/**
 * 设置显示位置：指定页(0~7)和列(0~127)
 */
static void OLED_SetPos(uint8_t page, uint8_t col)
{
    OLED_WriteCmd(0xB0 + page);                 /* 设置页地址 0xB0~0xB7 */
    OLED_WriteCmd((col & 0x0F));                /* 设置列地址低 4 位 */
    OLED_WriteCmd(0x10 | (col >> 4));           /* 设置列地址高 4 位 */
}

/* ============ 初始化 ============ */

