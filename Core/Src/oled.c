// x 表示第几列（0~127），y表示第几行（0~63）
void OLED_DrawPoint(uint8_t x, uint8_t y)
{
    uint8_t page = y / 8;
    uint8_t bit  = y % 8;
    OLED_GRAM[page][x] |= (0x01 << bit);   /* 只改显存，不直接发 */
}

void OLED_Refresh(void)
{
    uint8_t page;
    for (page = 0; page < 8; page++)
    {
        OLED_SetPos(page, 0);
        HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR << 1, OLED_DATA, I2C_MEMADD_SIZE_8BIT,
                          OLED_GRAM[page], 128, 1000);
    }
}
